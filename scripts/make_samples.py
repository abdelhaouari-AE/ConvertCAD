"""
make_samples.py — create the demonstration drawings in samples/.

    samples/sample_plan.pdf   vector A3 formwork plan at 1:100 (dimensions,
                              leaders, repeated columns and doors, grid
                              bubbles, dashed axes, hatch, title block) and
                              a second sheet rotated 90 degrees
    samples/sample_scan.pdf   the same plan as a 150 dpi scanned image, to
                              try raster tracing and OCR

They are generated by code (convertcad/samples.py), so they are not stored
in Git. The application's "Try the sample plan" button makes the same file.

    python scripts/make_samples.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from convertcad.samples import make_sample_plan, make_sample_scan  # noqa: E402


def main() -> int:
    folder = os.path.join(ROOT, "samples")
    os.makedirs(folder, exist_ok=True)
    plan = make_sample_plan(os.path.join(folder, "sample_plan.pdf"))
    scan = make_sample_scan(os.path.join(folder, "sample_scan.pdf"))
    for path in (plan, scan):
        print(f"Written: {os.path.relpath(path, ROOT)} "
              f"({os.path.getsize(path) / 1024:.0f} KB)")
    print("Try:  python -m convertcad --cli samples/sample_plan.pdf")
    return 0


if __name__ == "__main__":
    sys.exit(main())
